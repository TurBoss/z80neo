#!/usr/bin/env python3
"""Generate menu_rom.v: 6 pages x 10 lines x 38 chars of menu text."""

W = 38
LINES = 11

PAGES = {
0: ["  NullVDP Options",
    "  1 Cursor        : ",
    "  2 Local echo    : ",
    "  3 Palette       : ",
    "  4 Clear screen",
    "  5 Reset terminal",
    "  6 Help",
    "  7 About",
    "  8 Close",
    "",
    " Up/Down move  Left/Right change"],
1: ["  Help",
    "",
    "  F12        open / close",
    "  Up/Down    move selection",
    "  Left/Right change value",
    "  Enter      run / open",
    "  Esc        back / close",
    "",
    "  Keys are consumed locally",
    "  while the menu is open."],
2: ["  About",
    "",
    "  NullVDP - Tang Primer 20K",
    "  GW2A-LV18 + Dock, HDMI",
    "  80x30 cells, 16 colours",
    "  z80neo console over SPI",
    "",
    "  16-bit register SPI link",
    "  (doc/nullvdp_spi_protocol.md)"],
3: ["  Serial / terminal",
    "",
    "  Console : UART0 115200 8N1",
    "  SPI     : mode 0, 16-bit",
    "  Pins    : SCK T11 MOSI P11",
    "            MISO R11 CS T12",
    "",
    "  PS/2    : clk T7  data P6"],
4: ["  Colours",
    "",
    "  0 black   8 dark grey",
    "  1 blue    9 bright blue",
    "  2 green  10 bright green",
    "  3 cyan   11 bright cyan",
    "  4 red    12 bright red",
    "  5 magenta 13 bright magenta",
    "  6 brown  14 yellow",
    "  7 grey   15 white"],
5: ["  Credits",
    "",
    "  NullVDP FPGA terminal for",
    "  the z80neo (Tang Primer 20K).",
    "",
    "  Built with the open-source",
    "  Gowin flow (oss-cad-suite).",
    "",
    "  SPI slave + terminal: z80neo",
    "  project, GPLv3."],
}

SIZE = len(PAGES) * LINES * W
lines = []
lines.append("// ============================================================================")
lines.append("// menu_rom.v - generated by gen_menu_rom.py; 6 pages x 10 lines x 38 chars")
lines.append("// ============================================================================")
lines.append("module menu_rom (")
lines.append("    input             clk,")
lines.append("    input      [11:0] addr,")
lines.append("    output reg [7:0]  data")
lines.append(");")
lines.append("    reg [7:0] m [0:%d];" % (SIZE - 1))
lines.append("    integer i;")
lines.append("    initial begin")
lines.append("        for (i = 0; i < %d; i = i + 1) m[i] = 8'h20;" % SIZE)
for pg, plines in PAGES.items():
    for ln in range(LINES):
        text = plines[ln] if ln < len(plines) else ""
        text = (text + " " * W)[:W]
        base = (pg * LINES + ln) * W
        for c, ch in enumerate(text):
            o = ord(ch)
            if o < 32 or o > 126:
                o = 32
            lines.append("        m[%d] = 8'h%02X;" % (base + c, o))
lines.append("    end")
lines.append("    always @(posedge clk) data <= m[addr];")
lines.append("endmodule")

open("src/menu_rom.v", "w").write("\n".join(lines) + "\n")
print("wrote src/menu_rom.v: %d bytes of text ROM (%d words)" % (SIZE, SIZE))
