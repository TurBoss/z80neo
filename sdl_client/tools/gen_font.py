#!/usr/bin/env python3
"""Bake a PSF2 console font into sdl_client/src/font8x16.h.

Usage: gen_font.py [font.psfu] [out.h]

Defaults to the Linux console "default8x16" font, which is a PSF2 font with a
Unicode table mapping the 256 CP437 glyphs (box drawing, blocks, DEC graphics)
to their Unicode codepoints.
"""
import struct
import sys
import os

PSF2_MAGIC = bytes.fromhex("72b54a86")


def parse_psf2(data):
    if data[:4] != PSF2_MAGIC:
        raise SystemExit("not a PSF2 font")
    header_size, flags, length, charsize, height, width = struct.unpack(
        "<6I", data[8:32]
    )
    glyphs = []
    for i in range(length):
        off = header_size + i * charsize
        glyphs.append(data[off:off + charsize])
    table = data[header_size + length * charsize:]
    uni = []
    i = 0
    for _ in range(length):
        cps = []
        while i < len(table) and table[i] != 0xFF:
            b = table[i]
            if b < 0xC0:
                cp = b
                i += 1
            elif b < 0xE0:
                cp = ((b & 0x1F) << 6) | (table[i + 1] & 0x3F)
                i += 2
            elif b < 0xF0:
                cp = ((b & 0x0F) << 12) | ((table[i + 1] & 0x3F) << 6) | (
                    table[i + 2] & 0x3F
                )
                i += 3
            else:
                cp = ((b & 0x07) << 18) | ((table[i + 1] & 0x3F) << 12) | (
                    (table[i + 2] & 0x3F) << 6
                ) | (table[i + 3] & 0x3F)
                i += 4
            cps.append(cp)
        i += 1
        uni.append(cps)
    return width, height, length, glyphs, uni


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/kbd/consolefonts/default8x16.psfu"
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        os.path.dirname(__file__), "..", "src", "font8x16.h"
    )
    if src.endswith(".gz"):
        import gzip
        with gzip.open(src, "rb") as f:
            data = f.read()
    else:
        with open(src, "rb") as f:
            data = f.read()

    width, height, length, glyphs, uni = parse_psf2(data)
    if (width, height) != (8, 16):
        raise SystemExit(f"expected an 8x16 font, got {width}x{height}")

    pairs = {}
    for g, cps in enumerate(uni):
        for cp in cps:
            if cp and cp not in pairs:
                pairs[cp] = g
    entries = sorted(pairs.items())

    lines = []
    lines.append("// Generated by sdl_client/tools/gen_font.py -- do not edit.")
    lines.append("// Source: %s" % os.path.basename(src))
    lines.append("#ifndef FONT8X16_FONT_H")
    lines.append("#define FONT8X16_FONT_H")
    lines.append("")
    lines.append("#define FONT8X16_W 8")
    lines.append("#define FONT8X16_H 16")
    lines.append("#define FONT8X16_GLYPHS %d" % length)
    lines.append("")
    lines.append("static const unsigned char font8x16_bitmap[%d] = {" % (length * height))
    for g in range(length):
        row = ", ".join("0x%02x" % b for b in glyphs[g])
        lines.append("\t%s,%s" % (row, " // %3d %s" % (g, (",".join("U+%04X" % c for c in uni[g])))))
    lines.append("};")
    lines.append("")
    lines.append("typedef struct { unsigned short cp; unsigned char glyph; } Font8x16Map;")
    lines.append("")
    lines.append("static const Font8x16Map font8x16_map[%d] = {" % len(entries))
    for cp, g in entries:
        lines.append("\t{ 0x%04x, %3d }," % (cp, g))
    lines.append("};")
    lines.append("")
    lines.append("#define FONT8X16_MAP_LEN %d" % len(entries))
    lines.append("")
    lines.append("#endif")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s (%d glyphs, %d unicode entries)" % (out, length, len(entries)))


if __name__ == "__main__":
    main()
